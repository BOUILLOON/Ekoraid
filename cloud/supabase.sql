-- La playlist des 25 ans : collecte publique facultative sur Supabase.
-- Exécuter dans SQL Editor d'un projet Supabase neuf. Aucun fichier audio ici.
-- Réexécutable : conserve les données et les réglages existants.
begin;

create table if not exists public.playlist25_settings (
  singleton boolean primary key default true check (singleton),
  event_name text not null default 'La playlist des 25 ans',
  proposals_open boolean not null default true,
  votes_open boolean not null default true,
  invitation_required boolean not null default false,
  max_proposals integer not null default 10 check (max_proposals between 1 and 100),
  max_total_proposals integer not null default 2000 check (max_total_proposals between 1 and 10000),
  max_total_votes integer not null default 100000 check (max_total_votes between 1 and 500000),
  max_guests integer not null default 2000 check (max_guests between 1 and 10000)
);
insert into public.playlist25_settings(singleton) values (true) on conflict do nothing;
alter table public.playlist25_settings add column if not exists max_total_votes integer not null default 100000 check (max_total_votes between 1 and 500000);

create table if not exists public.playlist25_guests (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  nickname text not null check (char_length(nickname) between 1 and 50),
  created_at timestamptz not null default now()
);
create table if not exists public.playlist25_invitations (
  code_hash text primary key check (code_hash ~ '^[0-9a-f]{64}$'),
  guest_id uuid unique references public.playlist25_guests(id),
  created_at timestamptz not null default now()
);
create table if not exists public.playlist25_sources (
  id bigint generated by default as identity primary key,
  video_id text unique check (video_id is null or video_id ~ '^[A-Za-z0-9_-]{11}$'),
  url text,
  title text not null check (char_length(title) between 1 and 300),
  artist text not null default '' check (char_length(artist) <= 150),
  channel text not null default '',
  duration real,
  thumbnail text not null default '',
  created_at timestamptz not null default now(),
  check (url is null or (video_id is not null and url = 'https://www.youtube.com/watch?v=' || video_id))
);
create table if not exists public.playlist25_proposals (
  id bigint generated by default as identity primary key,
  source_id bigint not null unique references public.playlist25_sources(id),
  guest_id uuid not null references public.playlist25_guests(id),
  state text not null default 'pending' check (state in ('pending','approved','rejected','archived')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.playlist25_votes (
  proposal_id bigint not null references public.playlist25_proposals(id),
  guest_id uuid not null references public.playlist25_guests(id),
  created_at timestamptz not null default now(),
  primary key(proposal_id, guest_id)
);
create table if not exists public.playlist25_rate_limits (
  scope text not null,
  operation text not null,
  bucket bigint not null,
  count integer not null default 1,
  primary key(scope, operation, bucket)
);
create table if not exists public.playlist25_search_days (
  day date primary key,
  requests integer not null default 1
);
create index if not exists playlist25_proposals_guest on public.playlist25_proposals(guest_id);
create index if not exists playlist25_votes_guest on public.playlist25_votes(guest_id);

-- Aucune lecture/écriture directe depuis une clé publique, même via PostgREST.
alter table public.playlist25_settings enable row level security;
alter table public.playlist25_guests enable row level security;
alter table public.playlist25_invitations enable row level security;
alter table public.playlist25_sources enable row level security;
alter table public.playlist25_proposals enable row level security;
alter table public.playlist25_votes enable row level security;
alter table public.playlist25_rate_limits enable row level security;
alter table public.playlist25_search_days enable row level security;
revoke all on table public.playlist25_settings, public.playlist25_guests,
  public.playlist25_invitations, public.playlist25_sources, public.playlist25_proposals,
  public.playlist25_votes, public.playlist25_rate_limits, public.playlist25_search_days from public, anon, authenticated;
grant select, insert, update, delete on table public.playlist25_settings,
  public.playlist25_guests, public.playlist25_invitations, public.playlist25_sources,
  public.playlist25_proposals, public.playlist25_votes, public.playlist25_rate_limits, public.playlist25_search_days to service_role;
revoke all on sequence public.playlist25_sources_id_seq, public.playlist25_proposals_id_seq from public, anon, authenticated;
grant usage, select on sequence public.playlist25_sources_id_seq, public.playlist25_proposals_id_seq to service_role;

create or replace function public.playlist25_hash(value text) returns text
language sql immutable set search_path = pg_catalog
as $$ select encode(sha256(convert_to(value, 'UTF8')), 'hex') $$;

create or replace function public.playlist25_guest_id(p_token text) returns uuid
language sql stable security definer set search_path = pg_catalog, public
as $$ select id from public.playlist25_guests
  where p_token ~ '^[0-9a-f]{64}$' and token_hash = public.playlist25_hash(p_token) $$;

-- Les actions qui échouent retournent du JSON (pas RAISE), pour conserver le compteur.
-- Plafond global + plafond par jeton, jamais une identité basée sur IP/pseudo.
create or replace function public.playlist25_allow(p_token text, p_operation text,
  p_limit integer, p_global_limit integer) returns boolean
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare b bigint := floor(extract(epoch from clock_timestamp()) / 60); n integer;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then return false; end if;
  delete from public.playlist25_rate_limits where bucket < b - 10;
  insert into public.playlist25_rate_limits(scope,operation,bucket)
    values ('global',p_operation,b)
    on conflict(scope,operation,bucket) do update set count = playlist25_rate_limits.count + 1
      where playlist25_rate_limits.count < p_global_limit returning count into n;
  if n is null then return false; end if;
  n := null;
  insert into public.playlist25_rate_limits(scope,operation,bucket)
    values (public.playlist25_hash(p_token),p_operation,b)
    on conflict(scope,operation,bucket) do update set count = playlist25_rate_limits.count + 1
      where playlist25_rate_limits.count < p_limit returning count into n;
  return n is not null;
end $$;

-- L’Edge Function appelle cette RPC avec la clé publique, jamais service_role.
-- L’API YouTube optionnelle : 90 recherches/jour maximum (100 unités + détails).
create or replace function public.playlist25_search_budget(p_token text,
  p_official boolean default false) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare needs_invite boolean; gid uuid; n integer;
begin
  if not public.playlist25_allow(p_token,'search',20,120) then
    return jsonb_build_object('error','Trop de recherches. Réessayez dans une minute.','status',429);
  end if;
  select invitation_required into needs_invite from public.playlist25_settings where singleton;
  gid := public.playlist25_guest_id(p_token);
  if needs_invite and (gid is null or not exists(select 1 from public.playlist25_invitations where guest_id=gid)) then
    return jsonb_build_object('error','Choisissez votre pseudo avec le code d’invitation avant de chercher.','status',403);
  end if;
  if p_official then
    delete from public.playlist25_search_days where day < current_date - 7;
    insert into public.playlist25_search_days(day) values(current_date)
      on conflict(day) do update set requests=playlist25_search_days.requests+1
      where playlist25_search_days.requests < 90 returning requests into n;
    if n is null then return jsonb_build_object('error','Le quota gratuit de recherche du jour est atteint. Utilisez un lien ou une proposition manuelle.','status',429); end if;
  end if;
  return jsonb_build_object('allowed',true);
end $$;

