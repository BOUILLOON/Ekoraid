  from public.playlist25_settings where singleton $$;

create or replace function public.playlist25_public_item(p_id bigint, p_guest uuid) returns jsonb
language sql stable security definer set search_path = pg_catalog, public
as $$ select jsonb_build_object('id',p.id,'source_id',s.id,'nickname',g.nickname,
  'state',p.state,'sort_order',p.sort_order,'title',s.title,'artist',s.artist,
  'channel',s.channel,'duration',s.duration,'thumbnail',s.thumbnail,'url',s.url,
  'video_id',s.video_id,'status','pending','created_at',p.created_at,
  'votes',(select count(*) from public.playlist25_votes v where v.proposal_id=p.id),
  'voted',exists(select 1 from public.playlist25_votes v where v.proposal_id=p.id and v.guest_id=p_guest),
  'mine',p.guest_id=p_guest)
  from public.playlist25_proposals p
  join public.playlist25_sources s on s.id=p.source_id
  join public.playlist25_guests g on g.id=p.guest_id where p.id=p_id $$;

create or replace function public.playlist25_session(p_token text) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare g public.playlist25_guests;
begin
  if not public.playlist25_allow(p_token,'read',120,6000) then
    return jsonb_build_object('error','Trop de requêtes. Réessayez dans une minute.','status',429);
  end if;
  select * into g from public.playlist25_guests where id=public.playlist25_guest_id(p_token);
  return jsonb_build_object('guest',case when g.id is null then null else
    jsonb_build_object('id',g.id,'nickname',g.nickname) end,
    'csrf_token','','settings',public.playlist25_public_settings());
end $$;

create or replace function public.playlist25_identity(p_token text, p_nickname text,
  p_invitation_code text default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare g public.playlist25_guests; cfg public.playlist25_settings; invitation public.playlist25_invitations;
begin
  if not public.playlist25_allow(p_token,'identity',10,60) then
    return jsonb_build_object('error','Trop de demandes. Réessayez dans une minute.','status',429);
  end if;
  if p_nickname is null or char_length(btrim(p_nickname)) not between 1 and 50 or p_nickname ~ '[[:cntrl:]]' then
    return jsonb_build_object('error','Le pseudo doit contenir de 1 à 50 caractères.','status',422);
  end if;
  select * into cfg from public.playlist25_settings where singleton for update;
  select * into g from public.playlist25_guests where id=public.playlist25_guest_id(p_token) for update;
  if cfg.invitation_required and (g.id is null or not exists(select 1 from public.playlist25_invitations where guest_id=g.id)) then
    if p_invitation_code is null or char_length(p_invitation_code)>100 then
      return jsonb_build_object('error','Un code d’invitation individuel est nécessaire.','status',403);
    end if;
    select * into invitation from public.playlist25_invitations
      where code_hash=public.playlist25_hash(btrim(p_invitation_code)) for update;
    if invitation.code_hash is null or invitation.guest_id is not null then
      return jsonb_build_object('error','Code d’invitation invalide ou déjà utilisé.','status',403);
    end if;
  end if;
  if g.id is null then
    if (select count(*) from public.playlist25_guests) >= cfg.max_guests then
      return jsonb_build_object('error','La limite d’invités est atteinte. Contactez l’organisateur.','status',429);
    end if;
    insert into public.playlist25_guests(token_hash,nickname)
      values(public.playlist25_hash(p_token),btrim(p_nickname)) returning * into g;
  else
    update public.playlist25_guests set nickname=btrim(p_nickname) where id=g.id returning * into g;
  end if;
  if invitation.code_hash is not null then
    update public.playlist25_invitations set guest_id=g.id where code_hash=invitation.code_hash;
  end if;
  return jsonb_build_object('id',g.id,'nickname',g.nickname,'guest',jsonb_build_object('id',g.id,'nickname',g.nickname));
end $$;

create or replace function public.playlist25_list(p_token text, p_query text default '',
  p_sort text default 'popular', p_mine boolean default false) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare gid uuid; items jsonb;
begin
  if not public.playlist25_allow(p_token,'read',120,6000) then
    return jsonb_build_object('error','Trop de requêtes. Réessayez dans une minute.','status',429);
  end if;
  if char_length(coalesce(p_query,'')) > 150 then
    return jsonb_build_object('error','Recherche limitée à 150 caractères.','status',422);
  end if;
  gid := public.playlist25_guest_id(p_token);
  select coalesce(jsonb_agg(item order by rank desc,created_at desc,id desc),'[]'::jsonb) into items from (
    select public.playlist25_public_item(p.id,gid) as item,p.id,p.created_at,
      case when p_sort='recent' then 0 else (select count(*) from public.playlist25_votes v where v.proposal_id=p.id) end as rank
    from public.playlist25_proposals p join public.playlist25_sources s on s.id=p.source_id
    where p.state in ('pending','approved') and (not p_mine or p.guest_id=gid)
      and (coalesce(p_query,'')='' or position(lower(p_query) in lower(s.title || ' ' || s.artist || ' ' || s.channel))>0)
  ) listing;
  return jsonb_build_object('items',items);
end $$;

create or replace function public.playlist25_propose(p_token text, p_kind text,
  p_title text default null, p_artist text default '', p_video_id text default null) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare gid uuid; cfg public.playlist25_settings; sid bigint; pid bigint; duplicate_id bigint; title_value text; similar_items jsonb;
begin
  if not public.playlist25_allow(p_token,'proposal',15,100) then
    return jsonb_build_object('error','Trop de propositions. Réessayez dans une minute.','status',429);
  end if;
  gid := public.playlist25_guest_id(p_token);
  if gid is null then return jsonb_build_object('error','Choisissez d’abord un pseudo.','status',401); end if;
  select * into cfg from public.playlist25_settings where singleton for update;
  if not cfg.proposals_open then return jsonb_build_object('error','Les propositions sont fermées.','status',403); end if;
  if cfg.invitation_required and not exists(select 1 from public.playlist25_invitations where guest_id=gid) then
    return jsonb_build_object('error','Un code d’invitation est nécessaire. Renseignez-le avec votre pseudo.','status',403);
  end if;
  if p_kind not in ('manual','youtube') or p_kind is null then
    return jsonb_build_object('error','Type de proposition invalide.','status',422);
  end if;
  if char_length(coalesce(p_artist,''))>150 or coalesce(p_artist,'') ~ '[[:cntrl:]]' then
    return jsonb_build_object('error','Artiste limité à 150 caractères.','status',422);
  end if;
  if p_kind='youtube' then
    if p_video_id is null or p_video_id !~ '^[A-Za-z0-9_-]{11}$' then
      return jsonb_build_object('error','Identifiant YouTube invalide.','status',422);
    end if;
    -- Pas de fausse métadonnée : un titre saisi reste déclaré par l’invité.
    title_value := coalesce(nullif(btrim(p_title),''),'Vidéo YouTube ' || p_video_id || ' (titre à vérifier)');
    select p.id into duplicate_id from public.playlist25_proposals p
      join public.playlist25_sources s on s.id=p.source_id where s.video_id=p_video_id;
  else
    if p_video_id is not null then return jsonb_build_object('error','Source manuelle invalide.','status',422); end if;
    title_value := btrim(coalesce(p_title,''));
    select p.id into duplicate_id from public.playlist25_proposals p
      join public.playlist25_sources s on s.id=p.source_id
      where s.video_id is null and lower(s.title)=lower(title_value)
        and lower(s.artist)=lower(btrim(coalesce(p_artist,''))) order by p.id limit 1;
  end if;
  if char_length(title_value) not between 1 and 300 or title_value ~ '[[:cntrl:]]' then
    return jsonb_build_object('error','Titre obligatoire, limité à 300 caractères.','status',422);
  end if;
  if duplicate_id is not null then
    if exists(select 1 from public.playlist25_proposals where id=duplicate_id and state in ('pending','approved')) then
      return jsonb_build_object('duplicate',public.playlist25_public_item(duplicate_id,gid),'message','Ce morceau existe déjà. Vous pouvez voter pour lui.');
    end if;
    return jsonb_build_object('error','Cette source a déjà été examinée par l’organisateur.','status',409);
  end if;
  if (select count(*) from public.playlist25_proposals where guest_id=gid) >= cfg.max_proposals then
    return jsonb_build_object('error','Votre limite de propositions est atteinte.','status',429);
  end if;
  if (select count(*) from public.playlist25_proposals) >= cfg.max_total_proposals then
    return jsonb_build_object('error','La limite globale de propositions est atteinte.','status',429);
  end if;
  insert into public.playlist25_sources(video_id,url,title,artist)
    values(case when p_kind='youtube' then p_video_id else null end,
      case when p_kind='youtube' then 'https://www.youtube.com/watch?v=' || p_video_id else null end,
      title_value,btrim(coalesce(p_artist,''))) returning id into sid;
  insert into public.playlist25_proposals(source_id,guest_id) values(sid,gid) returning id into pid;
  select coalesce(jsonb_agg(public.playlist25_public_item(candidate.id,gid)),'[]'::jsonb) into similar_items from (
    select p.id from public.playlist25_proposals p join public.playlist25_sources s on s.id=p.source_id
    where p.id<>pid and p.state in ('pending','approved') and (
      lower(s.title)=lower(title_value) or (char_length(title_value)>=4 and char_length(s.title)>=4
        and (position(lower(s.title) in lower(title_value))>0 or position(lower(title_value) in lower(s.title))>0)))
    order by p.id limit 5
  ) candidate;
  return jsonb_build_object('item',public.playlist25_public_item(pid,gid),'similar',similar_items,
    'message',case when p_kind='youtube' then 'Lien enregistré. Les métadonnées seront vérifiées par l’organisateur.' else 'Proposition enregistrée.' end);
end $$;

create or replace function public.playlist25_vote(p_token text, p_proposal_id bigint,
  p_active boolean default true) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare gid uuid; enabled boolean; total bigint; maximum_votes integer; needs_invite boolean;
begin
  if not public.playlist25_allow(p_token,'vote',60,1000) then
    return jsonb_build_object('error','Trop de votes. Réessayez dans une minute.','status',429);
  end if;
  gid := public.playlist25_guest_id(p_token);
  if gid is null then return jsonb_build_object('error','Choisissez d’abord un pseudo.','status',401); end if;
  select votes_open,max_total_votes,invitation_required into enabled,maximum_votes,needs_invite from public.playlist25_settings where singleton for update;
  if not enabled then return jsonb_build_object('error','Les votes sont fermés.','status',403); end if;
  if needs_invite and not exists(select 1 from public.playlist25_invitations where guest_id=gid) then
    return jsonb_build_object('error','Un code d’invitation est nécessaire. Renseignez-le avec votre pseudo.','status',403);
  end if;
  perform 1 from public.playlist25_proposals where id=p_proposal_id and state in ('pending','approved') for update;
  if not found then return jsonb_build_object('error','Proposition introuvable.','status',404); end if;
  if p_active then
    if not exists(select 1 from public.playlist25_votes where proposal_id=p_proposal_id and guest_id=gid)
      and (select count(*) from public.playlist25_votes) >= maximum_votes then
      return jsonb_build_object('error','La limite globale de votes est atteinte. Contactez l’organisateur.','status',429);
    end if;
    insert into public.playlist25_votes(proposal_id,guest_id) values(p_proposal_id,gid) on conflict do nothing;
  else
    delete from public.playlist25_votes where proposal_id=p_proposal_id and guest_id=gid;
  end if;
  select count(*) into total from public.playlist25_votes where proposal_id=p_proposal_id;
  return jsonb_build_object('votes',total,'voted',exists(select 1 from public.playlist25_votes where proposal_id=p_proposal_id and guest_id=gid));
end $$;

-- Une seule requête : snapshot cohérent des propositions + votes pour le PC.
-- Jamais le hachage d’un jeton, les invitations ou les compteurs de sécurité.
create or replace function public.playlist25_snapshot() returns jsonb
language sql stable security definer set search_path = pg_catalog, public
as $$ select jsonb_build_object('schema_version',1,'exported_at',now(),
  'settings',public.playlist25_public_settings(),
  'guests',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'nickname',nickname,'created_at',created_at)),'[]'::jsonb) from public.playlist25_guests),
  'sources',(select coalesce(jsonb_agg(to_jsonb(s)),'[]'::jsonb) from public.playlist25_sources s),
  'proposals',(select coalesce(jsonb_agg(to_jsonb(p)),'[]'::jsonb) from public.playlist25_proposals p),
  'votes',(select coalesce(jsonb_agg(to_jsonb(v)),'[]'::jsonb) from public.playlist25_votes v)) $$;

create or replace function public.playlist25_create_invitations(p_count integer default 1) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare code text; codes jsonb := '[]'::jsonb; i integer;
begin
  if p_count not between 1 and 100 then return jsonb_build_object('error','Entre 1 et 100 codes par lot.','status',422); end if;
  for i in 1..p_count loop
    code := replace(gen_random_uuid()::text,'-','');
    insert into public.playlist25_invitations(code_hash) values(public.playlist25_hash(code));
    codes := codes || jsonb_build_array(code);
  end loop;
  return jsonb_build_object('codes',codes);
end $$;

-- Publication explicitement déclenchée depuis l’admin locale, clé service_role.
-- Validation de tout le lot avant écriture : aucun audio, URL arbitraire ou jeton.
create or replace function public.playlist25_admin_publish(p_settings jsonb, p_updates jsonb) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare entry jsonb; key text; updated integer := 0;
begin
  if jsonb_typeof(p_settings) is distinct from 'object' or jsonb_typeof(p_updates) is distinct from 'array' then
    return jsonb_build_object('error','Publication invalide.','status',422);
  end if;
  if jsonb_array_length(p_updates)>10000 then return jsonb_build_object('error','Lot public trop volumineux.','status',422); end if;
  for key in select jsonb_object_keys(p_settings) loop
    if key not in ('event_name','proposals_open','votes_open','invitation_required','max_proposals') then
      return jsonb_build_object('error','Réglage public non autorisé.','status',422);
    end if;
    if key='event_name' and (jsonb_typeof(p_settings->key) is distinct from 'string'
      or char_length(btrim(p_settings->>key)) not between 1 and 150 or (p_settings->>key) ~ '[[:cntrl:]]') then
      return jsonb_build_object('error','Nom d’événement invalide.','status',422);
    elsif key in ('proposals_open','votes_open','invitation_required') and jsonb_typeof(p_settings->key) is distinct from 'boolean' then
      return jsonb_build_object('error','Réglage booléen invalide.','status',422);
    elsif key='max_proposals' then
      if jsonb_typeof(p_settings->key) is distinct from 'number' or (p_settings->>key) !~ '^[1-9][0-9]{0,2}$' then
        return jsonb_build_object('error','Limite de propositions invalide.','status',422);
      end if;
      if (p_settings->>key)::integer > 100 then return jsonb_build_object('error','Limite maximale : 100.','status',422); end if;
    end if;
  end loop;
  for entry in select value from jsonb_array_elements(p_updates) loop
    if jsonb_typeof(entry) is distinct from 'object' then return jsonb_build_object('error','Proposition invalide.','status',422); end if;
    for key in select jsonb_object_keys(entry) loop
      if key not in ('id','state','title','artist','sort_order','merge_into') then return jsonb_build_object('error','Champ public non autorisé.','status',422); end if;
    end loop;
    if jsonb_typeof(entry->'id') is distinct from 'number' or (entry->>'id') !~ '^[1-9][0-9]{0,17}$'
      or jsonb_typeof(entry->'state') is distinct from 'string' or (entry->>'state') not in ('pending','approved','rejected','archived')
      or jsonb_typeof(entry->'title') is distinct from 'string' or char_length(btrim(entry->>'title')) not between 1 and 300
      or (entry->>'title') ~ '[[:cntrl:]]' or jsonb_typeof(entry->'artist') is distinct from 'string'
      or char_length(entry->>'artist')>150 or (entry->>'artist') ~ '[[:cntrl:]]'
      or jsonb_typeof(entry->'sort_order') is distinct from 'number' or (entry->>'sort_order') !~ '^-?[0-9]{1,9}$' then
      return jsonb_build_object('error','Métadonnées publiques invalides.','status',422);
    end if;
    if not exists(select 1 from public.playlist25_proposals where id=(entry->>'id')::bigint) then
      return jsonb_build_object('error','Une proposition distante manque. Récupérez la collecte avant de publier.','status',409);
    end if;
    if entry ? 'merge_into' then
      if jsonb_typeof(entry->'merge_into') is distinct from 'number' or (entry->>'merge_into') !~ '^[1-9][0-9]{0,17}$'
        or entry->>'state'<>'archived' or entry->>'merge_into'=entry->>'id' then
        return jsonb_build_object('error','Fusion publique invalide.','status',422);
      end if;
      if not exists(select 1 from jsonb_array_elements(p_updates) target
        where target->>'id'=entry->>'merge_into' and target->>'state'<>'archived' and not target ? 'merge_into') then
        return jsonb_build_object('error','Cible de fusion absente ou archivée.','status',422);
      end if;
    end if;
  end loop;
  if exists(select 1 from jsonb_array_elements(p_updates) e group by e->>'id' having count(*)>1) then
    return jsonb_build_object('error','Identifiant distant répété.','status',422);
  end if;
  update public.playlist25_settings set
    event_name=coalesce(p_settings->>'event_name',event_name),
    proposals_open=coalesce((p_settings->>'proposals_open')::boolean,proposals_open),
    votes_open=coalesce((p_settings->>'votes_open')::boolean,votes_open),
    invitation_required=coalesce((p_settings->>'invitation_required')::boolean,invitation_required),
    max_proposals=coalesce((p_settings->>'max_proposals')::integer,max_proposals) where singleton;
  for entry in select value from jsonb_array_elements(p_updates) loop
    update public.playlist25_proposals set state=entry->>'state',sort_order=(entry->>'sort_order')::integer
      where id=(entry->>'id')::bigint;
    update public.playlist25_sources set title=btrim(entry->>'title'),artist=btrim(entry->>'artist')
      where id=(select source_id from public.playlist25_proposals where id=(entry->>'id')::bigint);
    if entry ? 'merge_into' then
      insert into public.playlist25_votes(proposal_id,guest_id,created_at)
        select (entry->>'merge_into')::bigint,guest_id,created_at from public.playlist25_votes
        where proposal_id=(entry->>'id')::bigint on conflict(proposal_id,guest_id) do nothing;
      delete from public.playlist25_votes where proposal_id=(entry->>'id')::bigint;
    end if;
    updated := updated+1;
  end loop;
  return jsonb_build_object('updated',updated,'settings',public.playlist25_public_settings());
end $$;

