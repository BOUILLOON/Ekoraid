create or replace function public.playlist25_hash(value text) returns text
language sql immutable set search_path = pg_catalog
as $$ select encode(sha256(convert_to(value, 'UTF8')), 'hex') $$;

create or replace function public.playlist25_guest_id(p_token text) returns uuid
language sql stable security definer set search_path = pg_catalog, public
as $$ select id from public.playlist25_guests
  where p_token ~ '^[0-9a-f]{64}$' and token_hash = public.playlist25_hash(p_token) $$;

-- Les actions qui échouent retournent du JSON (pas RAISE), pour conserver le compteur.
-- Plafond global + plafond par jeton, jamais une identité basée sur IP/pseudo.
create or replace function public.playlist25_allow(p_token text, p_operation text,
  p_limit integer, p_global_limit integer) returns boolean
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare b bigint := floor(extract(epoch from clock_timestamp()) / 60); n integer;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then return false; end if;
  delete from public.playlist25_rate_limits where bucket < b - 10;
  insert into public.playlist25_rate_limits(scope,operation,bucket)
    values ('global',p_operation,b)
    on conflict(scope,operation,bucket) do update set count = playlist25_rate_limits.count + 1
      where playlist25_rate_limits.count < p_global_limit returning count into n;
  if n is null then return false; end if;
  n := null;
  insert into public.playlist25_rate_limits(scope,operation,bucket)
    values (public.playlist25_hash(p_token),p_operation,b)
    on conflict(scope,operation,bucket) do update set count = playlist25_rate_limits.count + 1
      where playlist25_rate_limits.count < p_limit returning count into n;
  return n is not null;
end $$;

-- L’Edge Function appelle cette RPC avec la clé publique, jamais service_role.
-- L’API YouTube optionnelle : 90 recherches/jour maximum (100 unités + détails).
create or replace function public.playlist25_search_budget(p_token text,
  p_official boolean default false) returns jsonb
language plpgsql security definer set search_path = pg_catalog, public
as $$
declare needs_invite boolean; gid uuid; n integer;
begin
  if not public.playlist25_allow(p_token,'search',20,120) then
    return jsonb_build_object('error','Trop de recherches. Réessayez dans une minute.','status',429);
  end if;
  select invitation_required into needs_invite from public.playlist25_settings where singleton;
  gid := public.playlist25_guest_id(p_token);
  if needs_invite and (gid is null or not exists(select 1 from public.playlist25_invitations where guest_id=gid)) then
    return jsonb_build_object('error','Choisissez votre pseudo avec le code d’invitation avant de chercher.','status',403);
  end if;
  if p_official then
    delete from public.playlist25_search_days where day < current_date - 7;
    insert into public.playlist25_search_days(day) values(current_date)
      on conflict(day) do update set requests=playlist25_search_days.requests+1
      where playlist25_search_days.requests < 90 returning requests into n;
    if n is null then return jsonb_build_object('error','Le quota gratuit de recherche du jour est atteint. Utilisez un lien ou une proposition manuelle.','status',429); end if;
  end if;
  return jsonb_build_object('allowed',true);
end $$;

